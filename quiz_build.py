"""quiz_build.py -- STEP 11. Build the quiz bank, once, offline.

WHAT IS GENERATED AND WHAT IS NOT. The model writes ONE thing: the Bengali
sentence that asks the question. It never supplies an answer and it never
supplies a distractor. The correct answer is a span lifted verbatim out of
the chunk, and every distractor is a span lifted verbatim out of a DIFFERENT
chunk. So a question can be wrong about its phrasing -- which a reviewer can
see -- but it cannot be wrong about its facts, which a reviewer cannot
easily see.

WHY DISTRACTORS COME FROM THE CORPUS. An invented distractor can accidentally
be correct: make up "২৬%" for a service charge and you may have named the
rate in a clause you did not read. A corpus distractor is wrong HERE and true
somewhere, which is what a distractor should be -- another band's approver,
the other manual's figure, an adjacent clause's rate. It also makes the
question discriminate: someone who has read the manual can tell the bands
apart, and someone guessing cannot.

TWO FACT KINDS, AND THE THIRD IS DELIBERATELY ABSENT.
    figure  a unit-bearing number: ২৪%, ৫,০০,০০০ টাকা, ১৮ মাস. Verbatim
            checkable, and the unit makes a same-unit distractor pool.
    role    a role name from roles.py, present in the chunk. "Who approves"
            is the question this corpus is most often asked and most often
            answered wrongly -- see the journal's approval-chain notes.
    rule    NOT BUILT. "A clause with a stated rule" has no verbatim answer
            span: the answer is a paraphrase of a sentence, so the "correct
            answer occurs verbatim in its chunk" check could not hold and
            the validation contract would have to be weakened for it. A
            weaker check on the one kind that needs it most is worse than
            not shipping that kind.

THE CLASS NO RULE REACHES, AND THE ONLY DEFENCE IS READING
-----------------------------------------------------------
An answer can be the single figure of its unit in its segment, verbatim,
correctly scoped, not a range end, not a duplicate -- and still not be what
the question asked. Every mechanical check in this file passes on all four
of these. They were found by a person reading the bank, and they were
deleted by hand:

  Q-016  "কিস্তি আদায় প্রক্রিয়ায় দায়িত্বপ্রাপ্ত পদবী কী?"  -- who COLLECTS
         instalments. Evidence: "উল্লিখিত কিস্তির অধিক জমা নিয়ে ঋণ বিতরণ
         করতে চাইলে ডিএম-এর অনুমোদন সাপেক্ষে ঋণ বিতরণ করা যাবে।" That is
         who APPROVES disbursement above a threshold. Different act.

  Q-025  "গ্রুপ মিটিংয়ের সর্বোচ্চ সময়সীমা কত বছর?"  -- how long a meeting
         may run. Evidence: "কমিটির মেয়াদকাল হবে ১ বছর।" That is the
         COMMITTEE'S TERM, not a meeting's duration.

  Q-028  "রুম বণ্টনে অগ্রাধিকার ভিত্তিতে এলাকা ব্যবস্থাপককে কত শতাংশ রুম?"
         -- a share of rooms. Evidence: "প্রকল্প বাড়িভাড়া হবে সহায়তা
         ভাতার ৫০%" -- a HOUSE RENT percentage of an allowance. Same number,
         unrelated quantity.

  Q-044  "গরু মোটাতাজাকরণ বিমার সর্বোচ্চ কভারেজ পরিমাণ কত টাকা?" -- a
         coverage ceiling. Evidence: "যদি ১টি ... গরুর বাজারমূল্য ১,০০,০০০
         টাকা হয়" -- the MARKET VALUE used in a worked example. An example
         input is not a limit.

The shape is always the same: the question names one quantity and the
segment supplies another that happens to share its unit. No test over
strings can see it, because nothing about the strings is wrong; the
mismatch is between what the Bengali sentence asks and what the Bengali
sentence beneath it says. ANYONE REGENERATING THIS BANK MUST READ IT. A
run that reports "N validated" has established that N questions are
well-formed, not that they are answerable.

NOTHING HERE MATCHES A PRODUCT NAME. Figures come from bn_shared's UNUM_RX
and roles from roles.py; Convention 2's registries stay the owners.

Usage:
  python quiz_build.py --limit 80          # writes quiz/bank.yaml
  python quiz_build.py --limit 80 --dry-run   # no model call, no write
"""

