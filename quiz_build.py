# ----------------------------------------------------------------- corpus
def load_chunks():
    out = []
    for tag in CORPORA:
        p = P / f"chunks_{tag}_final.jsonl"
        if not p.exists():
            continue
        for line in p.read_text(encoding="utf-8").splitlines():
            if line.strip():
                c = json.loads(line)
                c["manual_id"] = tag
                out.append(c)
    return out


def role_vocabulary():
    """[(display name, key)] from roles.py. No literal typed here."""
    import roles
    seen, out = set(), []
    for row in roles.ROLES:
        for name in (row[1], row[2], row[3]):
            n = (name or "").strip()
            # "সিডিও / পিও" is roles.py's PAIR LABEL for one role named
            # differently per manual, not a role anyone holds. Offered as an
            # option it is neither right nor wrong, which makes it unusable
            # as a distractor and absurd as an answer.
            if not n or "/" in n or n in seen:
                continue
            seen.add(n)
            out.append((n, row[0]))
    return out


# A LIST MARKER IS NOT A QUANTITY. UNUM_RX matches digits followed by a
# unit word, and in a numbered list "৩. কিস্তির শিডিউল অনুযায়ী..." that is
# the item number ৩ followed by কিস্তি. The first build produced exactly
# that: correct answer "৩. কিস্তি", distractor "২. কিস্তি" -- two list
# markers offered as rival quantities. A real figure never has a full stop
# and a space between the number and its unit; a decimal (২.৩৫%) has the
# stop but no space, so this keeps decimals.
_LIST_MARKER = _re.compile(r"\d\s*[.।]\s+")
# A CLAUSE NUMBER IS NOT A QUANTITY EITHER. "২.২.৩ মাসিক মুনাফা..." is
# clause ২.২.৩ followed by a word beginning মাস, and UNUM_RX read it as
# "২.২.৩ মাস". Two independent faults, so two tests:
#   two or more dots in the number  -> a clause number, not a figure
#   the unit is a PREFIX of a word  -> মাস inside মাসিক, not the unit মাস
_CLAUSEY = _re.compile(r"[\d০-৯]+[.।][\d০-৯]+[.।]")
_BN_LETTER = _re.compile(r"[অ-হ়-ৌড়-য়]")


def figure_spans(text):
    """Verbatim unit-bearing figures, as they appear. -> [(span, unit)]"""
    out = []
    for m in bn_shared.UNUM_RX.finditer(text or ""):
        span = m.group(0).strip()
        if _LIST_MARKER.search(span) or _CLAUSEY.search(span):
            continue
        tail = (text or "")[m.end(): m.end() + 1]
        if tail and _BN_LETTER.match(tail):
            continue                      # unit is the head of a longer word
        out.append((span, m.group(2)))
    return out


# A ROLE QUESTION NEEDS A SCOPE, NOT A SOLE OCCUPANT.
#
# The first rule was "exactly one role name in the chunk". It held the
# contract but threw away 67% of role candidates, and what it threw away
# were the responsibilities tables -- which is where most of what a field
# officer needs to know actually lives. A chunk saying "X does A, Y does B"
# supports "who does A?" perfectly well, with Y as the ideal distractor.
#
# So the unit of judgement is the SEGMENT, not the chunk: one line, one
# bullet, one table row -- the unit a single task is written in. A role is
# askable when some segment names it and no other role, and that segment
# carries enough text to be a task. The question can then name the task and
# have exactly one right answer.
#
# WHAT IS STILL REFUSED, and it is the case the brief names: a bare
# enumeration. "প্রত্যেক পিও/পিএ/পিএস (দাবি) প্রতিদিন সকালে..." names three
# roles doing the same thing, so no segment isolates one, and no question
# over it has a single answer. progoti_0050 is entirely of this shape.
_BULLET = _re.compile(r"[\n•]")
_MIN_TASK_CHARS = 25


def role_segments(text):
    """The chunk split into the units a single task is written in."""
    return [s.strip() for s in _BULLET.split(text or "") if s.strip()]


def role_scoped_facts(text, names, heading=""):
    """See below. `heading` is the chunk's heading path, excluded as a scope.
    """
    """[(role, segment)] -- roles this chunk can be asked about, with scope.

    A segment qualifies when it names exactly one role, that role is not
    inside a slash group, and there is enough text beside the name to be a
    task rather than a heading.
    """
    out, seen = [], set()
    # THE HEADING IS NOT A TASK. display_text begins with the heading path,
    # and a path like "৪.৪ এলাকা ব্যবস্থাপক - প্রগতি > ৪.৪.২ প্রকল্প নির্বাচন"
    # names a role and is long enough to pass the task-length test -- so a
    # question built on it asks "who is named in this section title", whose
    # answer is readable off the title itself. Measured on Q-165.
    head = (heading or "").strip()
    for seg in role_segments(text):
        if head and (seg in head or head.startswith(seg[:40])):
            continue
        present = {n for n in names if n in seg}
        if len(present) != 1:
            continue                      # nobody, or an enumeration
        role = present.pop()
        if not role_is_unambiguous(role, seg):
            continue                      # slash group inside the segment
        if len(seg) < len(role) + _MIN_TASK_CHARS:
            continue                      # a heading, not a task
        if not role_is_agent(role, seg):
            continue                      # named, but not the one acting
        if role in seen:
            continue                      # one question per role per chunk
        seen.add(role)
        out.append((role, seg))
    return out


# AGENT, NOT OBJECT. Measured on a sample question that passed every other
# check: the segment "...শাখা হিসাব কর্মকর্তাদের সার্বিক কার্যক্রম মনিটর করে..."
# names হিসাব কর্মকর্তা, so "whose duty is the monitoring?" scored it correct
# -- but it is the role being MONITORED. Bengali marks that on the noun: the
# object/genitive suffixes -কে and -দের attach directly to the role name.
# A role carrying one of those in the only segment that names it is not the
# actor, and the question would have the wrong answer.
# MEASURED OVER THE CORPUS, not guessed at. Counting what actually follows a
# role name across all 867 chunks turned up five case markers, not the two
# the first version had:
#
#   -কে  -দের  -কেই      object / plural  (already handled)
#   -র   -এর   -ের  ’র   GENITIVE         (missed, and the costly one)
#
# The genitive attaches with a hyphen (সিডিও-র), an apostrophe (সিডিও’র) or
# nothing at all (কর্মকর্তার). All three occur.
_OBJECT_SUFFIX = ("কে", "দের", "কেই",
                  "র", "এর", "ের",
                  "-র", "’র")


def role_is_agent(name, seg):
    """Does this segment have the role ACTING, rather than acted upon?

    ANY case-marked occurrence disqualifies, not merely "every". The first
    version returned True on the first bare occurrence, and the field case
    that broke it has both: "সিডিও কর্তৃক না আনা ২টি পাসবই যাচাই করে
    সিডিও-র কাজের মান যাচাই করবেন" -- the CDO is bare in a subordinate
    clause and genitive in the main one, and the verifier is somebody else
    entirely. A bare occurrence somewhere is not evidence that the role is
    the agent of the sentence.

    WHAT THIS COSTS, stated because it is a real loss and not free: a
    segment like "শাখা ব্যবস্থাপকের অনুমোদন সাপেক্ষে..." has the role
    genitive and the role IS the approver, so a correct question is refused
    with the wrong ones. Measured on the bank: 6 role questions drop, of
    which 4 are wrong, 1 is an overreach, and 1 is a good question lost.
    That trade is taken deliberately -- this bank trains officers, and a
    confidently wrong answer costs more than a missing question.
    """
    i = seg.find(name)
    while i != -1:
        tail = seg[i + len(name):]
        if any(tail.startswith(s) for s in _OBJECT_SUFFIX):
            return False                  # marked anywhere = not the agent
        i = seg.find(name, i + 1)
    return True


def agent_canary(chunks):
    """Convention 3. The rule must refuse a case observed to be wrong.

    Sliced from the stored chunk, never retyped: dabi_2025_0175 is the
    source of the question whose answer was the role being CHECKED. A
    positive control runs beside it, because a rule that refuses
    everything would also pass a negative-only canary.
    -> (ok, [lines])
    """
    by_id = {c["chunk_id"]: c for c in chunks}
    lines, ok = [], True

    neg = by_id.get("dabi_2025_0175")
    hit = None
    if neg:
        for seg in role_segments(neg.get("display_text") or ""):
            if "সিডিও" in seg and "-র" in seg:
                hit = seg
                break
    if hit is None:
        lines.append("  NEGATIVE  fixture segment not found in "
                     "dabi_2025_0175 -- canary cannot fire")
        ok = False
    else:
        refused = not role_is_agent("সিডিও", hit)
        lines.append(f"  NEGATIVE  observed failure refused: {refused}")
        ok = ok and refused

    pos = by_id.get("dabi_2025_0283_p4")
    kept = False
    if pos:
        names = [n for n, _k in role_vocabulary()]
        facts = role_scoped_facts(
            pos.get("display_text") or "", names,
            " > ".join(pos.get("heading_path") or []))
        kept = bool(facts)
    lines.append(f"  POSITIVE  a real agent segment still admitted: {kept}")
    ok = ok and kept
    lines.append("  " + ("DETECTED" if ok else "FAILED"))
    return ok, lines


def role_is_unambiguous(name, text):
    """Is this role the single plausible answer in this chunk?

    TWO WAYS IT IS NOT, both seen in the first build:

    1. SLASH GROUPS. The manuals write সিডিও/পিএ/পিএস for "any of these".
       Picking one member as THE answer makes the other two equally correct,
       and a reader who knows the manual cannot choose between them.
    2. RECIPIENT, NOT AGENT. "সিডিও/পিএসকে নির্দেশনা দেওয়া" is the PS being
       INSTRUCTED. A question asking whose duty it is has the wrong answer,
       and no verbatim check catches that because the name is right there.
       The slash test catches this case too, which is why it is the test.

    A chunk naming three or more distinct roles is dropped outright: it is a
    responsibilities table, and any of them answers "who does X".
    """
    i = text.find(name)
    while i != -1:
        before = text[max(0, i - 1): i]
        after = text[i + len(name): i + len(name) + 1]
        if "/" in (before + after):
            return False
        i = text.find(name, i + 1)
    return True


# ------------------------------------------------------------ candidates
def candidates(chunks, roles_vocab):
    """[(chunk, kind, correct_span, unit_or_None)] worth asking about."""
    out = []
    for c in chunks:
        if redact.is_excluded(c["chunk_id"]):
            continue
        clause, _disp = clause_pair(c)
        if not clause:
            continue                      # no clause to cite = not checkable
        text = c.get("display_text") or ""
        if len(text) < 80:
            continue
        for span, unit in figure_spans(text):
            out.append((c, "figure", span, unit))
        present = sorted({n for n, _k in roles_vocab if n in text})
        # EXACTLY ONE. Two named roles already make "who does X" ambiguous:
        # measured on Q-066, where a chunk naming শাখা ব্যবস্থাপক (Dabi) and
        # পিও (Progoti) produced a question with a different right answer per
        # manual. Three was too lax.
        if len(present) == 1 and role_is_unambiguous(present[0], text):
            out.append((c, "role", present[0], None))
    return out


def pools(cands):
    """Distractor pools: same unit for figures, all role names for roles."""
    fig = defaultdict(set)
    role = set()
    for _c, kind, span, unit in cands:
        if kind == "figure":
            fig[unit].add(span)
        else:
            role.add(span)
    return fig, role


# ONE POST, ONE OPTION. Distractors were once de-duplicated by spelling, and
# a post has several: a full name, an abbreviation, and for the field officer
# a different name in each programme. Q-006 offered বিভাগীয় ব্যবস্থাপক as the
# answer and ডিএম beside it -- the same post, so two options were right.
# Measured on the bank: 6 of 70 questions had two options for one post, 4 of
# them with the answer among the pair.
_POST_KEYS = None


def option_key(option):
    """What an option stands for: a role name's post key from roles.py's
    vocabulary (full name, abbreviation and per-programme name alike), or
    the canon'd text itself for anything that is not a role name."""
    global _POST_KEYS
    if _POST_KEYS is None:
        _POST_KEYS = {canon(n): k for n, k in role_vocabulary()}
    c = canon(option)
    return _POST_KEYS.get(c, c)


def pick_distractors(kind, correct, unit, chunk_text, fig_pool, role_pool,
                     rng, n=3):
    """Three corpus spans that are NOT in this chunk and NOT the answer,
    and no two of the four options the same post (option_key)."""
    pool = sorted(fig_pool.get(unit, set())) if kind == "figure" \
        else sorted(role_pool)
    seen = {option_key(correct)}
    out = []
    for cand in rng.sample(pool, k=len(pool)):
        if len(out) == n:
            break
        if option_key(cand) in seen:
            continue
        if occurs_as_word(cand, chunk_text):   # must be wrong FOR THIS CHUNK
            continue
        seen.add(option_key(cand))
        out.append(cand)
    return out


# A DISTRACTOR "IN THE CHUNK" MEANS AS A WORD, NOT AS LETTERS. The check was
# a substring test, and Q-043's পিএস was flagged in progoti_0090_p4 for the
# letters inside ডিপিএসসহ (DPS) -- a post that chunk never names. Bengali
# word boundaries are the registry topic gate's: its Bengali-block
# lookarounds and its closed list of endings, imported, not restated. The
# literal goes through bn_shared.canon_pattern rather than the registry's
# own, because that one keeps digit separators and a figure distractor like
# ১,০০,০০০ টাকা would then never match canon'd text.
def occurs_as_word(span, text):
    """Does `span` occur in `text` as a word of its own, with or without a
    case ending -- not inside a longer word? -> bool"""
    from registry import _BN, _ENDINGS
    rx = _re.compile("(?<![%s])%s%s(?![%s])" % (
        _BN, bn_shared.canon_pattern(span).pattern, _ENDINGS, _BN))
    return bool(rx.search(canon(text or "")))


# ------------------------------------------------------------- validation
_FIG_POOL = None


def valid_figure_spans(chunks):
    """Every figure span the corpus yields under TODAY's rules. Cached."""
    global _FIG_POOL
    if _FIG_POOL is None:
        _FIG_POOL = {sp for c in chunks
                     for sp, _u in figure_spans(c.get("display_text") or "")}
    return _FIG_POOL


def recheck_kind(q, chunk, roles_vocab, all_chunks):
    """The kind-specific rules, applied to an already-built question.

    Shared by the build and by --revalidate, so tightening a rule tightens
    both. A bank built under looser rules can then be re-filtered without
    paying for the questions again.
    """
    text = chunk.get("display_text") or ""
    bad = []
    if q["kind"] == "figure":
        if q["correct"] not in [sp for sp, _u in figure_spans(text)]:
            bad.append("correct span is no longer a valid figure "
                       "(list marker, clause number, or unit inside a word)")
        # THE DISTRACTORS TOO. They were drawn from a pool built under the
        # rules of the day, so tightening figure_spans leaves stale options
        # behind even when the answer is fine -- measured: a question kept
        # its correct span while still offering "২.২.৩ মাস", a clause
        # number, as a rival. A distractor a reader can dismiss on sight
        # teaches nothing and makes the question look broken.
        pool = valid_figure_spans(all_chunks)
        for o in q["options"]:
            if o != q["correct"] and o not in pool:
                bad.append(f"distractor is not a valid figure: {o!r}")
    elif q["kind"] == "role":
        # THE SEGMENT RULE, not the old chunk-level count. A chunk may name
        # several roles as long as some segment scopes this one to a task;
        # that is the whole point of the relaxation. Checking the chunk
        # count here would refuse exactly what role_scoped_facts admits --
        # measured: it threw away 26 of 32 freshly generated questions
        # AFTER they were paid for, because selection and validation were
        # applying different rules. One rule, one place.
        names = [n for n, _k in roles_vocab]
        askable = {r for r, _seg in role_scoped_facts(
            text, names, " > ".join(chunk.get("heading_path") or []))}
        if q["correct"] not in askable:
            present = sorted({n for n in names if n in text})
            bad.append(
                f"role not scoped to a task in any segment "
                f"(chunk names {len(present)} role(s))")
        # AND IN THE SEGMENT THIS QUESTION ACTUALLY CITES. Asking only
        # whether the chunk can support SOME question about the role lets a
        # bad one through whenever the chunk also has a good segment
        # elsewhere -- measured: Q-168 survived on a sibling segment while
        # its own evidence read "সিডিও-র কাজের ... যাচাই করবেন", the CDO
        # being checked. The explanation is the evidence shown to the
        # officer, so it is the text the rule has to hold on.
        seg = q.get("explanation") or ""
        if not role_is_agent(q["correct"], seg):
            bad.append("role is case-marked in the cited segment; "
                       "it is not the agent there")
        elif len({n for n in names if n in seg}) != 1:
            bad.append("cited segment names more than one role")
    return bad


# RULE 2. A range has two ends and neither is an answer. Q-027's answer was
# ০০%, the lower bound of "০০% - ৩০%" -- true of nothing on its own. The
# separators the manuals use between the ends of a range, measured: ASCII
# hyphen, en dash, em dash, এবং the words থেকে / হতে / পর্যন্ত.
_RANGE_SEP = ("-", "–", "—", "থেকে",
              "হতে", "পর্যন্ত")


def is_range_fragment(span, seg):
    """Is this figure one END of a range rather than a value?"""
    i = seg.find(span)
    while i != -1:
        before = seg[max(0, i - 14): i]
        after = seg[i + len(span): i + len(span) + 14]
        if any(sep in after for sep in _RANGE_SEP) and                 bn_shared.UNUM_RX.search(after):
            return True                   # "X - Y": this is the low end
        if any(sep in before for sep in _RANGE_SEP) and                 bn_shared.NUM_RX.search(before):
            return True                   # "Y - X": this is the high end
        i = seg.find(span, i + 1)
    return False


def is_zero_answer(span):
    """০০% / 00 and friends: a placeholder, never a fact."""
    digits = "".join(ch for ch in fold_digits_local(span) if ch.isdigit())
    return bool(digits) and set(digits) == {"0"}


def fold_digits_local(s):
    from bnnorm import fold_digits
    return fold_digits(s or "")


# RULE 5. The question must not hand over the answer, and a substring test
# is not enough: Q-055 asked for "আঞ্চলিক অফিসের ব্যবস্থাপকের পদবী" and the
# answer was আঞ্চলিক ব্যবস্থাপক -- not a substring, but every word of the
# answer is already in the question. Head-word test instead.
def question_leaks_answer(question, correct, kind):
    """Does the question already contain its own answer?

    KIND-DEPENDENT, because the first version was not and over-fired. It
    dropped short tokens before testing, so "৫০ টাকা" reduced to ["টাকা"]
    and then matched every question mentioning টাকা -- which is nearly
    every figure question. Twelve were refused for "containing the answer"
    when they contained only its unit.

      figure  the NUMERAL must appear. The unit is what a question is
              obliged to say; the number is what it is asking for.
      role    every word of the role name must appear. Q-055 asked for
              "আঞ্চলিক অফিসের ব্যবস্থাপকের পদবী" and answered আঞ্চলিক
              ব্যবস্থাপক -- not a substring, but both words already given.
    """
    q = question or ""
    if kind == "figure":
        nums = _re.findall(r"[\d০-৯][\d০-৯,.]*",
                           correct or "")
        return any(x in q for x in nums if len(x) >= 2)
    words = [w for w in (correct or "").split() if len(w) >= 3]
    return bool(words) and all(w in q for w in words)


# RULE 6. One value per question. A segment listing four premiums cannot
# support "what is the premium?" -- Q-019, Q-032 and Q-039 each asked that
# of a four-row table. If the cited segment carries more than one figure of
# the SAME unit, the question is under-specified whatever it says.
def same_unit_rivals(span, seg):
    unit = None
    for sp, u in figure_spans(seg):
        if sp == span:
            unit = u
            break
    if unit is None:
        return 0
    return len({sp for sp, u in figure_spans(seg)
                if u == unit and sp != span})


def validate(q, chunk_text):
    """-> [reason, ...]. Empty means the question may be written."""
    bad = []
    if q["correct"] not in chunk_text:
        bad.append("correct answer not verbatim in its chunk")
    for d in q["options"]:
        if d == q["correct"]:
            continue
        if occurs_as_word(d, chunk_text):
            bad.append(f"distractor occurs in the chunk: {d!r}")
    if len({canon(o) for o in q["options"]}) != 4:
        bad.append("options not distinct after canon()")
    if len(q["options"]) != 4:
        bad.append(f"{len(q['options'])} options, expected 4")
    if redact.is_excluded(q["chunk_id"]):
        bad.append("chunk is withheld from retrieval")
    if not q["question_bn"].strip():
        bad.append("empty question text")
    if question_leaks_answer(q["question_bn"], q["correct"], q["kind"]):
        bad.append("question contains the answer")

    # RULE 1, and it is the cheapest check that should always have existed.
    # "Occurs in the chunk" is not the guarantee a reader needs: the
    # explanation is the ONLY evidence shown beside the answer, so an
    # answer absent from it is unsupported on the page even when the chunk
    # holds it somewhere. Q-009's ৭০বছর appears nowhere in its segment.
    seg = q.get("explanation") or ""
    if q["correct"] not in seg:
        bad.append("answer not in the explanation shown to the reader")

    if q["kind"] == "figure":
        if is_range_fragment(q["correct"], seg):
            bad.append("answer is one end of a range, not a value")
        if is_zero_answer(q["correct"]):
            bad.append("answer is a zero placeholder")
        rivals = same_unit_rivals(q["correct"], seg)
        if rivals:
            bad.append(f"segment holds {rivals} other figure(s) of the same "
                       f"unit; question is under-specified")
    return bad


def explanation_sentence(text, correct):
    """The chunk sentence the answer comes from, verbatim."""
    parts = [s.strip() for s in text.replace("।", "।\n").split("\n")
             if s.strip()]
    for s in parts:
        if correct in s:
            return s if len(s) <= 400 else s[:400].rstrip() + "..."
    i = text.find(correct)
    return text[max(0, i - 120): i + 120].strip()


# --------------------------------------------------------------- the model
def ask_questions(batch, provider, model):
    """One call per batch. -> [question_bn] aligned with batch."""
    import generate
    lines = []
    for i, (c, kind, correct, _u) in enumerate(batch, 1):
        head = " > ".join(c.get("heading_path") or [])
        body = (c.get("display_text") or "")[:PASSAGE_CHARS]
        lines.append(f"--- ITEM {i}\nheading: {head}\nfact ({kind}): "
                     f"{correct}\npassage: {body}")
    user = ("\n\n".join(lines) + f"\n\n--- OUTPUT\nWrite {len(batch)} "
            "question(s), one per line, numbered '1.' to "
            f"'{len(batch)}.'. Bengali only.")
    text, meta = generate.complete(SYSTEM, user)
    out = []
    for ln in (text or "").splitlines():
        ln = ln.strip()
        if not ln:
            continue
        head, _sep, rest = ln.partition(".")
        out.append(rest.strip() if head.strip().isdigit() else ln)
    while len(out) < len(batch):
        out.append("")
    return out[:len(batch)], meta


def viable_facts(c, roles_vocab):
    """[(kind, span, seg)] this chunk offers under the ANSWER-LEVEL rules.

    Everything decidable before a question exists: the candidate filters,
    the range end, the zero placeholder, the same-unit rivals, the role
    scope and agent tests. Applying them at SELECTION is the whole point of
    this pass -- the earlier builds paid for questions that validation then
    refused, 26 of 32 in one case. A rule that can run before the spend
    should never run after it.
    """
    out = []
    text = c.get("display_text") or ""
    heading = " > ".join(c.get("heading_path") or [])
    names = [n for n, _k in roles_vocab]
    for sp, _u in figure_spans(text):
        seg = next((s for s in role_segments(text) if sp in s), text)
        if is_range_fragment(sp, seg) or is_zero_answer(sp):
            continue
        if same_unit_rivals(sp, seg):
            continue
        out.append(("figure", sp, seg))
    for role, seg in role_scoped_facts(text, names, heading):
        out.append(("role", role, seg))
    return out


def build_v3(chunks, args):
    """One more build, with the rules applied BEFORE the tokens."""
    import yaml
    import generate
    rng = random.Random(args.seed + 7)
    roles_vocab = role_vocabulary()
    dst = OUT.with_name(OUT.stem + "_validated.yaml")
    doc = yaml.safe_load(dst.read_text(encoding="utf-8")) if dst.exists()         else {"meta": {}, "questions": []}
    have_chunks = {q["chunk_id"] for q in doc.get("questions") or []}
    mf = {}
    mp = Path("data/processed/chunk_manifest.json")
    if mp.exists():
        mf = {c["chunk_id"]: c
              for c in json.loads(mp.read_text(encoding="utf-8"))["chunks"]}
    used_groups = {mf.get(c, {}).get("dup_group") for c in have_chunks} - {None}

    pool = []
    for c in chunks:
        cid = c["chunk_id"]
        if cid in have_chunks or redact.is_excluded(cid):
            continue
        clause, _d = clause_pair(c)
        if not clause:
            continue
        if len(c.get("display_text") or "") < 80:
            continue
        g = mf.get(cid, {}).get("dup_group")
        if g and g in used_groups:
            continue
        facts = viable_facts(c, roles_vocab)
        if facts:
            pool.append((c, clause, facts))

    # SPREAD ACROSS CLAUSES. Round-robin over (manual, clause) buckets, so a
    # clause with forty viable chunks cannot take forty of the slots. The
    # first builds clustered on chapter 1 and 5 for exactly that reason.
    buckets = defaultdict(list)
    for c, clause, facts in pool:
        buckets[(c["manual_id"], clause)].append((c, facts))
    for b in buckets.values():
        rng.shuffle(b)
    keys = sorted(buckets)
    rng.shuffle(keys)

    want_role = int(args.build_v3 * args.role_share + 0.999)
    picked, seen_chunk = [], set()
    # two passes: fill the role quota first, then anything
    for need_role in (True, False):
        exhausted = False
        while not exhausted and len(picked) < args.build_v3:
            exhausted = True
            for k in keys:
                if len(picked) >= args.build_v3:
                    break
                if need_role and sum(1 for x in picked if x[1] == "role")                         >= want_role:
                    break
                for idx, (c, facts) in enumerate(buckets[k]):
                    if c["chunk_id"] in seen_chunk:
                        continue
                    cand = [f for f in facts
                            if (f[0] == "role") == need_role] or                         ([] if need_role else facts)
                    if not cand:
                        continue
                    kind, span, seg = cand[0]
                    seen_chunk.add(c["chunk_id"])
                    picked.append((c, kind, span, seg))
                    exhausted = False
                    break
    return _plan_or_generate(picked, doc, dst, args, roles_vocab, chunks,
                             len(pool), len(buckets))


