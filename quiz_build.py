def _generate_v3(picked, doc, dst, args, roles_vocab, chunks, rng):
    """Generate for the drawn facts, appending to the validated bank.

    THE BUDGET IS A HARD STOP, checked before each batch rather than after
    the run. A build that overruns leaves no reserve and the day's limit is
    per model -- see generate.TPD_LIMIT. Stopping early keeps whatever was
    already written.
    """
    import yaml
    import generate
    SENT.parent.mkdir(parents=True, exist_ok=True)
    with SENT.open("w", encoding="utf-8", newline=NL) as fh:
        for c, _k, _s, _g in picked:
            fh.write(json.dumps({"question_id": c["chunk_id"],
                                 "question_bn": "", "chunks": [{
                                     "chunk_id": c["chunk_id"],
                                     "display_text": c.get("display_text")}]},
                                ensure_ascii=False) + NL)
    guard = generate.check_corpus_guard(SENT, args.provider, CORPUS_REASON)
    print(f"corpus guard         : {guard}")
    generate.configure(args.provider, args.model)
    start_spend = generate.ledger_used(args.provider, args.model)

    fig_pool, role_pool = pools(
        [(c, k, s, None) for c, k, s, _g in picked])
    all_roles = {n for n, _k in roles_vocab}
    all_figs = defaultdict(set)
    for c in chunks:
        for sp, u in figure_spans(c.get("display_text") or ""):
            all_figs[u].add(sp)

    rows, refused, stopped = [], [], None
    for start in range(0, len(picked), args.batch):
        spent = generate.ledger_used(args.provider, args.model) - start_spend
        if spent >= args.max_spend:
            stopped = (f"budget cap reached: {spent:,} spent this build, "
                       f"cap {args.max_spend:,}")
            break
        batch = picked[start:start + args.batch]
        try:
            qs, _m = ask_questions([(c, k, s, None) for c, k, s, _g in batch],
                                   args.provider, args.model)
        except generate.ProviderError as e:
            stopped = f"provider failed at item {start}: {e}"
            break
        for (c, kind, span, seg), qtext in zip(batch, qs):
            text = c.get("display_text") or ""
            unit = unit_of(span, seg) if kind == "figure" else None
            ds = pick_distractors(kind, span, unit, text,
                                  all_figs if kind == "figure" else {},
                                  all_roles, rng)
            if len(ds) < 3:
                refused.append((c["chunk_id"], ["fewer than 3 distractors"]))
                continue
            clause, clause_display = clause_pair(c)
            opts = [span] + ds
            rng.shuffle(opts)
            q = {"id": "NEW", "kind": kind,
                 "question_bn": (qtext or "").strip(),
                 "chunk_id": c["chunk_id"], "manual_id": c["manual_id"],
                 "clause": clause, "clause_display": clause_display,
                 "correct": span, "options": opts,
                 "explanation": seg if len(seg) <= 400 else seg[:400] + "..."}
            why = validate(q, text) + recheck_kind(q, c, roles_vocab, chunks)
            (rows if not why else refused).append(
                q if not why else (c["chunk_id"], why))
        print(f"  batch {start // args.batch + 1}: {len(rows)} kept, "
              f"{len(refused)} refused")

    merged = list(doc.get("questions") or [])
    x = cross_question_drops(merged + rows, {})
    new_start = len(merged)
    keep_new = [q for i, q in enumerate(rows)
                if (new_start + i) not in x]
    for i, q in enumerate(rows):
        if (new_start + i) in x:
            refused.append((q["chunk_id"], [x[new_start + i]]))
    merged = merged + keep_new
    for i, q in enumerate(merged, 1):
        q["id"] = f"Q-{i:03d}"
    spent = generate.ledger_used(args.provider, args.model) - start_spend

    print(NL + f"new questions kept   : {len(keep_new)}")
    print(f"refused              : {len(refused)}")
    from collections import Counter as _C
    grouped = _C()
    for _cid, why in refused:
        for w in why:
            grouped[str(w).split("(")[0].strip()] += 1
    for w, n in grouped.most_common():
        print(f"   {n:>3}  {w}")
    if stopped:
        print(f"STOPPED EARLY: {stopped}")
    print(f"tokens spent         : {spent:,}")

    meta = dict(doc.get("meta") or {})
    meta.update({"n_questions": len(merged), "corpus_guard": guard,
                 "v3_added": len(keep_new), "v3_tokens": spent})
    dst.write_text(BANK_HEADER + yaml.safe_dump(
        {"meta": meta, "questions": merged},
        allow_unicode=True, sort_keys=False, width=100), encoding="utf-8")
    # The new ids, so the v3 review can render only what has not been read.
    Path("quiz/_v3_new_ids.json").write_text(
        json.dumps([q["id"] for q in merged[new_start:]]), encoding="utf-8")
    print(f"-> {dst}  ({len(merged)} questions)")
    return 0

