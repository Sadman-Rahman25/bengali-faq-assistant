# ---------------------------------------------- whole-bank (cross-question)
# RULES 3 AND 4 cannot be decided one question at a time: both are about a
# question's relationship to the REST of the bank.
# MONEY IS ONE UNIT AT FOUR SCALES. UNUM_RX reports টাকা, হাজার, লক্ষ and
# কোটি as different units, so "১ লক্ষ" and "২০০০০০ টাকা" looked unrelated
# and rule 4 never compared them -- they are 100,000 and 200,000 taka, two
# different limits on the same §7.1 clause. Normalise to taka before
# comparing. Scales read off the unit word; nothing product-shaped here.
_MONEY_SCALE = {"টাকা": 1,
                "হাজার": 1000,
                "লক্ষ": 100000,
                "কোটি": 10000000}


def unit_class(unit):
    """The unit a comparison should use. All money scales collapse to one."""
    return "money" if unit in _MONEY_SCALE else unit


def span_value(span, unit):
    """The span as a number, in taka for money. -> float or None"""
    from bnnorm import fold_digits
    m = bn_shared.NUM_RX.search(fold_digits(span or ""))
    if not m:
        return None
    try:
        v = float(m.group(0).replace(",", "").rstrip("."))
    except ValueError:
        return None
    return v * _MONEY_SCALE.get(unit, 1)


def unit_of(span, seg):
    for sp, u in figure_spans(seg):
        if sp == span:
            return u
    return None


def cross_question_drops(rows, manifest):
    """[(index, reason)] for questions that only a whole-bank view refuses."""
    drops = {}

    # RULE 3. dup_group, not chunk_id. 516 of 867 chunks are byte-identical
    # across the two manuals, so "one question per chunk" let a twin pair
    # through as two questions -- Q-046/Q-058 and Q-056/Q-061 are the same
    # question asked twice, and the distinct-chunks check reported 48 of 48
    # because the ids differ. dedupe.py already decided which chunks are the
    # same content, at a threshold of exactly 1.000; this just reads it.
    # RULE 3b. dup_group is dedupe.py's judgement at similarity exactly
    # 1.000, and it correctly declines near-identical pairs -- so
    # dabi_2025_0074 and progoti_0084 both carry dup_group None while
    # carrying the same sentence about the same post. A duplicate QUIZ
    # QUESTION is a property of the question, not of the chunk: same answer
    # plus either the same wording or the same cited evidence. The
    # evidence clause is what catches the near-identical pair, whose
    # question wordings differ.
    seen_q = {}
    for i, q in enumerate(rows):
        key_a = (canon(q["correct"]), canon(q["question_bn"]))
        key_b = (canon(q["correct"]), canon(q.get("explanation") or ""))
        for k in (key_a, key_b):
            if k in seen_q and seen_q[k] != i:
                drops.setdefault(i, (
                    f"duplicate question of {rows[seen_q[k]]['id']} "
                    f"(same answer and same "
                    f"{'wording' if k is key_a else 'evidence'})"))
                break
        else:
            seen_q.setdefault(key_a, i)
            seen_q.setdefault(key_b, i)

    seen_group = {}
    for i, q in enumerate(rows):
        g = (manifest.get(q["chunk_id"]) or {}).get("dup_group")
        if not g:
            continue
        if g in seen_group:
            drops[i] = (f"duplicate of {rows[seen_group[g]]['id']} "
                        f"via dup_group {g}")
        else:
            seen_group[g] = i

    # RULE 4. A table-of-authority row is not the table's rule. Two questions
    # off §7.1 gave কর্মসূচি প্রধান a ৫ লক্ষ limit and a ৩ লক্ষ limit, both
    # true of their own row and neither true of the clause. Where a clause
    # yields two questions with the same unit and DIFFERENT answers, each
    # question has to name the row it means; if its text shares no
    # distinguishing token with its own segment, it is asking about the
    # clause and the clause has no single answer.
    by_clause = defaultdict(list)
    for i, q in enumerate(rows):
        if q["kind"] == "figure":
            by_clause[(q["manual_id"], q["clause"])].append(i)
    for _key, idxs in by_clause.items():
        if len(idxs) < 2:
            continue
        for i in idxs:
            qi = rows[i]
            ui = unit_of(qi["correct"], qi.get("explanation") or "")
            ci, vi = unit_class(ui), span_value(qi["correct"], ui)
            rivals = []
            for j in idxs:
                if j == i:
                    continue
                uj = unit_of(rows[j]["correct"],
                             rows[j].get("explanation") or "")
                if unit_class(uj) != ci:
                    continue
                vj = span_value(rows[j]["correct"], uj)
                # Different VALUE, not merely a different string: ১ লক্ষ and
                # ১,০০,০০০ টাকা are the same limit written two ways and are
                # not rivals.
                if vi is not None and vj is not None and vi == vj:
                    continue
                if rows[j]["correct"] != qi["correct"]:
                    rivals.append(j)
            if not rivals:
                continue
            # Does the question name something only ITS segment says?
            # THE FULL BENGALI BLOCK. The first version used
            # [অ-হ়-ৌ], which omits the virama
            # ্, so every conjunct split: আঞ্চলিক came out as 'চলিক'
            # and ব্যবস্থাপক as 'থাপক'. Fragments match nothing in a
            # question, so the distinctive-token test silently passed
            # everything and rule 4 never fired on Q-031/Q-037.
            mine = set(_re.findall(r"[ঀ-৿]{4,}",
                                   qi.get("explanation") or ""))
            theirs = set()
            for j in rivals:
                theirs |= set(_re.findall(
                    r"[ঀ-৿]{4,}",
                    rows[j].get("explanation") or ""))
            # A ROLE IS NOT A ROW KEY. An authority table lists the same
            # approver against several subjects at several limits, so
            # "how much can the RM approve" is still unanswerable even
            # though it names the RM -- measured on Q-031 (১ লক্ষ) and
            # Q-037 (২০০০০০ টাকা), both §7.1, both naming a post and
            # neither naming what is being approved. The distinguishing
            # token has to be the SUBJECT of the row or the band.
            role_words = set()
            for nm, _k in role_vocabulary():
                role_words |= {w for w in nm.split() if len(w) >= 4}
            distinctive = {w for w in mine - theirs - role_words
                           if w in (qi.get("question_bn") or "")}
            if not distinctive:
                drops.setdefault(i, (
                    "same clause and unit as "
                    f"{rows[rivals[0]]['id']} with a different answer, and "
                    "the question names no row to tell them apart"))
    return drops


def revalidate(chunks):
    """Re-filter an existing bank under the current rules. No tokens."""
    import yaml
    if not OUT.exists():
        print(f"no bank at {OUT}")
        return 1
    print("CANARY -- agent rule")
    ok_canary, lines = agent_canary(chunks)
    for ln in lines:
        print(ln)
    if not ok_canary:
        print(NL + "FATAL: the agent rule is not behaving. Bank untouched.")
        return 2

    doc = yaml.safe_load(OUT.read_text(encoding="utf-8"))
    by_id = {c["chunk_id"]: c for c in chunks}
    roles_vocab = role_vocabulary()
    kept, dropped = [], []
    for q in doc.get("questions") or []:
        c = by_id.get(q["chunk_id"])
        if c is None:
            dropped.append((q["id"], q["chunk_id"], ["chunk not in corpus"]))
            continue
        why = validate(q, c.get("display_text") or "") +             recheck_kind(q, c, roles_vocab, chunks)
        (kept if not why else dropped).append(
            q if not why else (q["id"], q["chunk_id"], why))
    # Whole-bank rules, applied to what survived the per-question ones.
    mf = {}
    mp = Path("data/processed/chunk_manifest.json")
    if mp.exists():
        mf = {c["chunk_id"]: c
              for c in json.loads(mp.read_text(encoding="utf-8"))["chunks"]}
    x = cross_question_drops(kept, mf)
    if x:
        for i in sorted(x):
            dropped.append((kept[i]["id"], kept[i]["chunk_id"], [x[i]]))
        kept = [q for i, q in enumerate(kept) if i not in x]

    # UNIQUE IDS. add_roles numbered from len(questions)+100 and collided
    # with the ids an earlier build had already used -- Q-159, Q-164, Q-167
    # and Q-169 each named two different questions, which makes the bank
    # uncitable and silently merged two of them in an earlier analysis.
    # Renumbered here, in bank order, once.
    seen_ids, renumbered = set(), 0
    for i, q in enumerate(kept, 1):
        want = f"Q-{i:03d}"
        if q["id"] != want:
            renumbered += 1
        q["id"] = want
        seen_ids.add(want)
    print(f"revalidate: {len(kept)} kept, {len(dropped)} dropped, "
          f"{renumbered} renumbered ({len(seen_ids)} unique ids)")
    from collections import Counter as _C
    grouped = _C()
    for _qid, _cid, why in dropped:
        for w in why:
            grouped[w.split("(")[0].strip()] += 1
    print("  dropped by rule:")
    for w, c in grouped.most_common():
        print(f"    {c:>3}  {w}")
    for qid, cid, why in dropped:
        print(f"  {qid} {cid}: {'; '.join(why)}")
    meta = dict(doc.get("meta") or {})
    meta.update({"n_questions": len(kept),
                 "n_dropped_on_revalidate": len(dropped)})
    # NEVER OVER THE INPUT. An earlier run applied a rule that proved wrong
    # and overwrote the bank with its output, destroying 33 questions that
    # had been paid for; they were recoverable only because
    # out/quiz_review.md still held them. A validator that edits its own
    # input in place makes every rule change irreversible.
    dst = OUT.with_name(OUT.stem + "_validated.yaml")
    dst.write_text(
        BANK_HEADER
        + yaml.safe_dump({"meta": meta, "questions": kept},
                         allow_unicode=True, sort_keys=False, width=100),
        encoding="utf-8")
    print(f"-> {dst}  ({len(kept)} kept; {OUT} untouched)")
    return 0


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--limit", type=int, default=80)
    # MEASURED: gpt-oss-120b reasons before it writes, and generate.py caps
    # completions at max_tokens=1024. At 8 items per call it spent the
    # whole 1024 on reasoning and returned an EMPTY string -- 66 of 80
    # questions refused as "empty question text" while the tokens were
    # billed. Three items and a 500-character passage fit: 608 output
    # tokens for three questions, all three returned.
    ap.add_argument("--batch", type=int, default=3)
    ap.add_argument("--seed", type=int, default=11)
    ap.add_argument("--provider", default="groq")
    ap.add_argument("--model", default="openai/gpt-oss-120b")
    ap.add_argument("--dry-run", action="store_true",
                    help="select and validate without calling the model")
    ap.add_argument("--build-v3", type=int, default=0, metavar="N",
                    help="select N candidates from chunks not already used, "
                         "applying every ANSWER-LEVEL rule before spending a "
                         "token, holding a role share and spreading across "
                         "clauses. Appends to bank_validated.yaml.")
    ap.add_argument("--role-share", type=float, default=0.62,
                    help="minimum share of the draw that must be role "
                         "questions (default 0.62, the current bank's)")
    ap.add_argument("--max-spend", type=int, default=40000,
                    help="refuse to start a batch that would take the day's "
                         "spend past this")
    ap.add_argument("--plan-only", action="store_true",
                    help="report the draw and its distribution, spend nothing")
    ap.add_argument("--add-roles", type=int, default=0, metavar="N",
                    help="generate N role questions from chunks not already "
                         "in the bank and APPEND them. The figure half is "
                         "left alone; re-buying it would cost tokens for "
                         "nothing.")
    ap.add_argument("--revalidate", action="store_true",
                    help="re-apply today's rules to an existing bank.yaml "
                         "and drop what no longer passes. No model call.")
    args = ap.parse_args()

    rng = random.Random(args.seed)
    chunks = load_chunks()
    if args.revalidate:
        return revalidate(chunks)
    if args.build_v3:
        return build_v3(chunks, args)
    if args.add_roles:
        return add_roles(chunks, args)
    roles_vocab = role_vocabulary()
    cands = candidates(chunks, roles_vocab)
    fig_pool, role_pool = pools(cands)
    print(f"corpus            : {len(chunks)} chunks")
    print(f"candidate facts   : {len(cands)}  "
          f"({sum(1 for c in cands if c[1] == 'figure')} figure, "
          f"{sum(1 for c in cands if c[1] == 'role')} role)")
    print(f"distractor pools  : "
          f"{sum(len(v) for v in fig_pool.values())} figure spans in "
          f"{len(fig_pool)} unit(s), {len(role_pool)} role names")

    # One question per chunk at most, so the bank is not ten variations of
    # the same table.
    rng.shuffle(cands)
    chosen, used_chunks = [], set()
    for c, kind, correct, unit in cands:
        if len(chosen) >= args.limit:
            break
        if c["chunk_id"] in used_chunks:
            continue
        text = c.get("display_text") or ""
        ds = pick_distractors(kind, correct, unit, text, fig_pool, role_pool,
                              rng)
        if len(ds) < 3:
            continue
        used_chunks.add(c["chunk_id"])
        chosen.append((c, kind, correct, unit, ds))
    print(f"selected          : {len(chosen)} (one per chunk, "
          f"seed {args.seed})")

    if args.dry_run:
        print("\n--dry-run: no model call, nothing written")
        return 0

    import generate
    SENT.parent.mkdir(parents=True, exist_ok=True)
    with SENT.open("w", encoding="utf-8", newline="\n") as fh:
        for c, _k, _a, _u, _d in chosen:
            fh.write(json.dumps({"question_id": c["chunk_id"],
                                 "question_bn": "", "chunks": [{
                                     "chunk_id": c["chunk_id"],
                                     "display_text": c.get("display_text")}]},
                                ensure_ascii=False) + "\n")
    try:
        guard = generate.check_corpus_guard(SENT, args.provider, CORPUS_REASON)
    except generate.ProviderError as e:
        print(f"\n{e}")
        return 1
    print(f"corpus guard      : {guard}")

    generate.configure(args.provider, args.model)
    used_before = generate.ledger_used(args.provider, args.model)
    rows, refused = [], []
    for start in range(0, len(chosen), args.batch):
        batch = chosen[start:start + args.batch]
        try:
            qs, _meta = ask_questions([(c, k, a, u) for c, k, a, u, _d in batch],
                                      args.provider, args.model)
        except generate.ProviderError as e:
            print(f"  provider failed at item {start}: {e}")
            break
        for (c, kind, correct, _unit, ds), qtext in zip(batch, qs):
            clause, clause_display = clause_pair(c)
            opts = [correct] + ds
            rng.shuffle(opts)
            text = c.get("display_text") or ""
            q = {
                "id": f"Q-{len(rows) + len(refused) + 1:03d}",
                "kind": kind,
                "question_bn": qtext.strip(),
                "chunk_id": c["chunk_id"],
                "manual_id": c["manual_id"],
                "clause": clause,
                "clause_display": clause_display,
                "correct": correct,
                "options": opts,
                "explanation": explanation_sentence(text, correct),
            }
            why = validate(q, text)
            if why:
                refused.append((q["id"], c["chunk_id"], why))
            else:
                rows.append(q)
        print(f"  batch {start // args.batch + 1}: "
              f"{len(rows)} kept, {len(refused)} refused")

    spent = generate.ledger_used(args.provider, args.model) - used_before
    print(f"\ngenerated         : {len(rows)}")
    print(f"refused           : {len(refused)}")
    for qid, cid, why in refused[:12]:
        print(f"  {qid} {cid}: {'; '.join(why)}")
    if len(refused) > 12:
        print(f"  ... and {len(refused) - 12} more")
    print(f"tokens spent      : {spent:,}")

    if not rows:
        print("nothing valid to write")
        return 1
    OUT.parent.mkdir(parents=True, exist_ok=True)
    import yaml
    OUT.write_text(
        "# quiz/bank.yaml -- generated by quiz_build.py. REVIEW BEFORE USE.\n"
        "# Facts and options are verbatim corpus spans; only question_bn was\n"
        "# written by a model. See quiz_build.py's docstring.\n"
        + yaml.safe_dump({"meta": {"generated_by": "quiz_build.py",
                                   "provider": args.provider,
                                   "model": args.model,
                                   "seed": args.seed,
                                   "corpus_guard": guard,
                                   "n_questions": len(rows),
                                   "n_refused": len(refused)},
                          "questions": rows},
                         allow_unicode=True, sort_keys=False, width=100),
        encoding="utf-8")
    print(f"-> {OUT}  ({len(rows)} questions)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
